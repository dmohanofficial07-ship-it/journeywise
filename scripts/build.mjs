import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.resolve(root,'dist');
if(path.dirname(out)!==root||path.basename(out)!=='dist')throw new Error('Unsafe build output path.');
const names=['index.html','style.css','app.js','engine.js','booking.js','accounts.js','demo.html','demo.css','demo.js','demo-engine.js'];
for(const name of names)await fs.access(path.join(root,'public',name));
await fs.mkdir(path.join(root,'.sites-runtime'),{recursive:true});
const types={html:'text/html; charset=utf-8',css:'text/css; charset=utf-8',js:'text/javascript; charset=utf-8'};
const assets={};
for(const name of names)assets['/'+name]={body:await fs.readFile(path.join(root,'public',name),'utf8'),type:types[name.split('.').at(-1)]};
await fs.writeFile(path.join(root,'.sites-runtime/text-assets.json'),JSON.stringify(assets));
await fs.rm(out,{recursive:true,force:true});
await fs.mkdir(path.join(out,'server'),{recursive:true});
await fs.mkdir(path.join(out,'client'),{recursive:true});
await fs.copyFile(path.join(root,'public/konkan-railway.jpg'),path.join(out,'client/konkan-railway.jpg'));
await build({entryPoints:[path.join(root,'server/worker.js')],outfile:path.join(out,'server/index.js'),bundle:true,format:'esm',platform:'browser',target:'es2022',minify:false,logLevel:'info'});
await fs.mkdir(path.join(out,'.openai'),{recursive:true});
await fs.copyFile(path.join(root,'.openai/hosting.json'),path.join(out,'.openai/hosting.json'));
console.log('Built worker with API and embedded text assets.');
